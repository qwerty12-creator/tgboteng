import { levelFor, xpBar } from '../core/xp.js';
import { escapeHtml } from '../core/insights.js';

export function menuText(user, stats) {
  const level = levelFor(user?.xp ?? 0);
  const lines = [
    '<b>YOUR ENGLISH JOURNEY</b>',
    `<i>${escapeHtml(user?.first_name || 'friend')}, твой личный дневник английского</i>`,
    '',
    `${level.emoji} <b>${level.name}</b> · ${level.xp} XP${level.next ? ` / ${level.next}` : ''}`,
    `<code>${xpBar(user?.xp ?? 0, 12)}</code>`,
    `🔥 Стрик: ${user?.streak_current ?? 0} дн. · рекорд ${user?.streak_best ?? 0} дн.`,
    '',
    `📖 Записей: ${stats.diary} · 📝 Слов: ${stats.words} · 🎯 Упражнений: ${stats.grammar.total}`,
  ];
  if (stats.dueWords) lines.push(`🔁 К повторению слов: <b>${stats.dueWords}</b>`);
  lines.push('', 'Выбери раздел 👇');
  return lines.join('\n');
}

export function startText(user, isNew) {
  const hello = escapeHtml(user?.first_name || 'friend');
  if (!isNew) {
    return ['С возвращением! 👋', '', 'Продолжим путешествие в английский? Выбери раздел ниже.'].join('\n');
  }
  return [
    `<b>Привет, ${hello}!</b>`,
    '',
    'Это <b>YOUR ENGLISH JOURNEY</b> — твой личный дневник английского языка.',
    '',
    'Здесь ты:',
    '• пишешь короткие записи на английском и видишь разбор;',
    '• собираешь свой словарь и повторяешь слова;',
    '• тренируешь грамматику по слабым темам;',
    '• учишься писать тексты и получаешь фидбек;',
    '• разговариваешь на английском с AI-собеседником;',
    '• видишь прогресс, стрики, XP и достижения.',
    '',
    'Главное правило: <i>маленькие шаги каждый день</i>. Начни с одной записи в дневнике — это 2 минуты.',
    '',
    'Загляни в ❓ Помощь, там всё по разделам.',
  ].join('\n');
}

